export const DAY_MS = 86_400_000;
export const EPOCH = Date.UTC(2026, 9, 21);
export function getDailyFact(date = new Date()) {
  const milliseconds = date.getTime();
  if (!Number.isFinite(milliseconds)) throw new TypeError('A valid date is required.');
  const day = Math.floor(milliseconds / DAY_MS) - Math.floor(EPOCH / DAY_MS);
  const index = ((day % FACTS.length) + FACTS.length) % FACTS.length;
  return {fact: FACTS[index], index, date:date.toISOString().slice(0,10)};
}
export function millisecondsUntilNextDay(date = new Date()) {
  return DAY_MS - ((date.getTime() % DAY_MS) + DAY_MS) % DAY_MS;
}
